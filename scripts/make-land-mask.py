"""Make src/engine/landMask.ts: which 1-degree cells of the world are land, for the dotted globe.

Rasterizes Natural Earth's public-domain 1:110m land polygons (each cell is land when its center is inside
a polygon) into a 360 x 180 bit grid, packed as base64. Row 0 is 89.5 N, column 0 is 179.5 W. Run:

    python scripts/make-land-mask.py              # downloads the outlines
    python scripts/make-land-mask.py land.geojson  # or uses a local copy
"""
import base64
import json
import os
import sys
import urllib.request

URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'engine', 'landMask.ts')


def rings(geojson):
    for f in geojson['features']:
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            for ring in poly:
                yield ring


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding='utf-8') as fh:
            data = json.load(fh)
    else:
        with urllib.request.urlopen(URL) as resp:
            data = json.load(resp)
    # Per ring: its edges, plus a bounding box to skip most cells quickly.
    rs = []
    for ring in rings(data):
        xs = [p[0] for p in ring]; ys = [p[1] for p in ring]
        rs.append((min(xs), max(xs), min(ys), max(ys), ring))
    bits = bytearray(360 * 180 // 8)
    land = 0
    for row in range(180):
        lat = 89.5 - row
        for col in range(360):
            lon = -179.5 + col
            inside = False
            for x0, x1, y0, y1, ring in rs:
                if lon < x0 or lon > x1 or lat < y0 or lat > y1:
                    continue
                # Even-odd ray cast, so holes in a polygon come out as water.
                for i in range(len(ring) - 1):
                    ax, ay = ring[i][0], ring[i][1]
                    bx, by = ring[i + 1][0], ring[i + 1][1]
                    if (ay > lat) != (by > lat) and lon < ax + (lat - ay) * (bx - ax) / (by - ay):
                        inside = not inside
            if inside:
                n = row * 360 + col
                bits[n >> 3] |= 0x80 >> (n & 7)
                land += 1
    b64 = base64.b64encode(bytes(bits)).decode('ascii')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// Generated by scripts/make-land-mask.py from Natural Earth 1:110m land (public domain). Do not edit.\n')
        fh.write('// 360 x 180 one-degree cells, 1 = land, packed 8 per byte (high bit first), row 0 = 89.5 N, column 0 = 179.5 W.\n')
        fh.write("export const LAND_MASK = '" + b64 + "';\n")
    print(f'{land} land cells of {360 * 180} ({land / 648:.1f}%), {len(b64)} chars -> {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
